#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Build and run the transform tests: every tests/test_*.cpp twice (sanitized, then with the binary's own -O3 flags),
# then tests/test_flow.sh. Exits non-zero on any failure.
#
#   tests/run_tests.sh GRE_DIR        GRE_DIR: a GRE clone built by scripts/build_gre.sh (with or without EXTRA)
#
# Each tests/test_*.cpp is one program (other .cpp files are helpers, e.g. flow_eval.cpp for test_flow.sh), compiled
# with -O1 -g -fsanitize=address,undefined -fno-sanitize-recover=all (any UB report fails the test) and the include
# paths, shims and defines of build_gre.sh: macOS GRE_DIR/build/mac/include,
# -mcpu=native and the libc++ defines; Linux -march=native, -fopenmp and the activated conda environment's TBB. Plus
# -I REPO/include -I GRE_DIR/src/competitor -I GRE_DIR/src. No UBSan check is exempted, in GRE's competitors either
# (the gate never builds raw ALEX on 2^64 - 1, where its predict overflowed an int). Unlike the binary, NDEBUG is not
# defined, so assert() stays on in the tests and in the competitors (TEST_NDEBUG=1 adds -DNDEBUG). ASan leak checks are
# off (Linux; none on macOS arm64): leaks are not the contract. Each test then runs again as <test>-O3, compiled like
# the GRE binary (build_gre.sh's -O3 -DNDEBUG flags, no sanitizer): exactness must hold for the code that is timed,
# where inlining and vectorization differ from -O1 (TEST_RELEASE=0 skips this pass). Binaries and logs: build/tests/.
# Each test, and test_flow.sh, sees:
#   GRE_DIR, REPO_ROOT    absolute paths
#   SAMPLE_DIR            data/sample.py output (default REPO/data/samples): if SAMPLE_DIR/SAMPLES.txt exists, every
#                         sample it lists is passed to test_index as an argument (real-data cases); SAMPLE_DIR= skips
#   FLOW_DIR              passed through: test_index also runs nf on FILE when FLOW_DIR/<basename>.flow exists
#   PYTHON                a python3 that imports numpy and torch (probed: $PYTHON, python3, /usr/bin/python3)
#   GRET_CXX              compiler wrapper with all the flags above: "$GRET_CXX x.cpp -o x" (build/tests/cxx-O3: the
#                         release flags)
#   GRET_BUILD            build/tests, for binaries and scratch files
# Options:
#   TESTS="a b"           only these (basenames, e.g. "test_pwlcdf test_flow")
#   TESTS_BG=1            run although a timed run is active, every step under background priority (taskpolicy -b,
#                         nice -n 20); without it the script refuses then (exit 2)
# tests/test_build_unchanged.sh is separate (it clones GRE).
set -euo pipefail
[ $# = 1 ] || { echo "usage: tests/run_tests.sh GRE_DIR" >&2; exit 2; }
GRE_DIR=$(cd "$1" && pwd)
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$ROOT/build/tests
mkdir -p "$OUT"

LOW=()
if pgrep -f '[s]cratchpad/mac_run.sh' >/dev/null 2>&1 || pgrep -f '[-]-keys_file=' >/dev/null 2>&1; then
    [ "${TESTS_BG:-0}" = 1 ] || { echo "a timed run is active (pgrep -fl 'mac_run.sh|--keys_file='): rerun after it," \
                                      "or TESTS_BG=1 for background priority" >&2; exit 2; }
    if [ "$(uname -s)" = Darwin ]; then LOW=(taskpolicy -b nice -n 20); else LOW=(nice -n 20); fi
fi

SAN=(-O1 -g -fno-omit-frame-pointer -fsanitize=address,undefined -fno-sanitize-recover=all)
INC=(-I"$ROOT/include" -I"$GRE_DIR/src/competitor" -I"$GRE_DIR/src")
if [ "${TEST_NDEBUG:-0}" = 1 ]; then INC+=(-DNDEBUG); fi
if [ "$(uname -s)" = Darwin ]; then
    [ -d "$GRE_DIR/build/mac/include" ] || { echo "no $GRE_DIR/build/mac/include: build it with scripts/build_gre.sh" >&2; exit 2; }
    CXX=${GRE_CLANG:-/usr/bin/clang++}
    # build_gre.sh's macOS flags without -O3 -DNDEBUG (see above); REL: the binary's own optimization flags
    FLAGS=(-faligned-new -mcpu=native -include cstdint -std=gnu++17 -D_LIBCPP_ENABLE_CXX17_REMOVED_RANDOM_SHUFFLE
           '-D__float128=long double' -I"$GRE_DIR/build/mac/include")
    REL=(-g -O3 -DNDEBUG)
    LIBS=()
else
    : "${CONDA_PREFIX:?activate the conda environment build_gre.sh used}"
    CXX=${CXX:-c++}
    # GRE's CMakeLists.txt: add_compile_options, C++17, OpenMP, TBB and jemalloc include dirs (jemalloc not linked: ASan)
    FLAGS=(-faligned-new -march=native -include cstdint -std=gnu++17 -fopenmp -I"$CONDA_PREFIX/include")
    REL=(-g -O3 -DNDEBUG)  # GRE's add_compile_options plus CMake's Release flags
    LIBS=(-L"$CONDA_PREFIX/lib" -Wl,-rpath,"$CONDA_PREFIX/lib" -ltbb -pthread)
fi
# libraries after the sources, for linkers that drop unused -l given first
wrapper() {  # wrapper FILE FLAG...: an exec line with the compiler, the flags, the sources, the libraries
    { echo '#!/usr/bin/env bash'; echo '# generated by tests/run_tests.sh: the test compiler and flags'
      printf 'exec'; printf ' %q' "$CXX" "${@:2}"; printf ' "$@"'
      if [ -n "${LIBS[*]+x}" ]; then printf ' %q' "${LIBS[@]}"; fi; echo; } > "$1"
    chmod +x "$1"
}
wrapper "$OUT/cxx" "${SAN[@]}" "${FLAGS[@]}" "${INC[@]}"
INC_REL=(); for f in "${INC[@]}"; do [ "$f" = -DNDEBUG ] || INC_REL+=("$f"); done  # REL defines NDEBUG itself
wrapper "$OUT/cxx-O3" "${REL[@]}" "${FLAGS[@]}" "${INC_REL[@]}"

PY=""
for c in "${PYTHON:-}" python3 /usr/bin/python3; do
    [ -n "$c" ] && "$c" -c 'import numpy, torch' >/dev/null 2>&1 && { PY=$(command -v "$c"); break; }; done
[ -n "$PY" ] || { PY=${PYTHON:-python3}; echo "WARNING: no python3 with numpy and torch; PYTHON=$PY" >&2; }
export GRE_DIR REPO_ROOT=$ROOT SAMPLE_DIR=${SAMPLE_DIR-$ROOT/data/samples} PYTHON=$PY GRET_CXX=$OUT/cxx GRET_BUILD=$OUT
export ASAN_OPTIONS=${ASAN_OPTIONS:-detect_leaks=0} UBSAN_OPTIONS=${UBSAN_OPTIONS:-print_stacktrace=1}

want() { [ -z "${TESTS:-}" ] || case " $TESTS " in *" $1 "*) true ;; *) false ;; esac; }
pass=0; fail=0; failed=""
result() {  # result NAME STATUS LOG
    if [ "$2" = 0 ]; then pass=$((pass + 1)); echo "PASS $1 (${SECONDS}s)"
    else fail=$((fail + 1)); failed="$failed $1"; echo "FAIL $1: exit $2 ($3)"; tail -n 40 "$3" | sed 's/^/   | /'; fi
}
n=0
REAL=()  # the samples for test_index, as listed (sha256sum format) in SAMPLES.txt
if [ -n "$SAMPLE_DIR" ] && [ -f "$SAMPLE_DIR/SAMPLES.txt" ]; then
    while read -r _ f; do [ -n "$f" ] && REAL+=("$SAMPLE_DIR/$f"); done < "$SAMPLE_DIR/SAMPLES.txt"
    echo "test_index gets ${#REAL[@]} samples from $SAMPLE_DIR"; fi
PASSES=(cxx:); [ "${TEST_RELEASE:-1}" = 0 ] || PASSES+=(cxx-O3:-O3)  # wrapper:suffix
for src in "$ROOT"/tests/test_*.cpp; do
    [ -f "$src" ] || continue
    base=$(basename "$src" .cpp); want "$base" || continue
    ARGS=(); [ "$base" != test_index ] || ARGS=(${REAL[@]+"${REAL[@]}"})
    for pv in "${PASSES[@]}"; do
        cc=${pv%%:*}; t=$base${pv#*:}; n=$((n + 1))
        SECONDS=0; echo "== $t: compile ($cc)"
        if ! ${LOW[@]+"${LOW[@]}"} "$OUT/$cc" "$src" -o "$OUT/$t" > "$OUT/$t.compile.log" 2>&1; then
            result "$t (compile)" 1 "$OUT/$t.compile.log"; continue; fi
        echo "== $t: run"; st=0
        (cd "$OUT" && ${LOW[@]+"${LOW[@]}"} "./$t" ${ARGS[@]+"${ARGS[@]}"}) > "$OUT/$t.log" 2>&1 || st=$?
        result "$t" "$st" "$OUT/$t.log"
    done
done
if want test_flow; then
    n=$((n + 1)); SECONDS=0; echo "== test_flow.sh"
    if [ -f "$ROOT/tests/test_flow.sh" ]; then
        st=0; ${LOW[@]+"${LOW[@]}"} bash "$ROOT/tests/test_flow.sh" > "$OUT/test_flow.log" 2>&1 || st=$?
        result test_flow "$st" "$OUT/test_flow.log"
    else echo "missing tests/test_flow.sh" > "$OUT/test_flow.log"; result test_flow 1 "$OUT/test_flow.log"; fi
fi
[ "$n" -gt 0 ] || { echo "no test selected (TESTS='${TESTS:-}')" >&2; exit 1; }
echo "$pass passed, $fail failed${failed:+:$failed}; logs in $OUT"
[ "$fail" = 0 ]
