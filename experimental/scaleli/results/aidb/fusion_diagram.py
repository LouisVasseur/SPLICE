#!/usr/bin/env python3
"""The fusion idea in one picture: two axes, two methods, one straight line.

Needs matplotlib.  /usr/bin/python3 results/aidb/fusion_diagram.py [--slide]

A lookup is a map from key to position. A learned index wants that map to be a straight line,
because then one multiply-add finds the answer. There are exactly two axes you can bend to get it:

    NFL bends the INPUT  axis:  key  ->  z = f(key)          (a learned monotone warp)
    CSV bends the OUTPUT axis:  rank ->  slot                (virtual points that hold no record)

Real data: the 489 region fences of the books 2M uniform sample, the case where both matter.
Probe counts under each panel are the measured cost of the resulting root model
(results/aidb_joint/joint_results.json).
"""
import json, math, os, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "aidb_joint" / "verify"))
import indep as I
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = pathlib.Path(__file__).resolve().parent
S = HERE.parent.parent
BLUE, ORANGE, TEAL, GRAY = "#2a78d6", "#eb6834", "#1baf7a", "#b9c0c6"
INK, MUTED, GRID = "#17242f", "#6b7480", "#d8d7d0"
SLIDE = "--slide" in sys.argv
DS, ALPHA = "books", 4.0

keys = I.load(str(S / f"data/samples/{DS}_2M_uniform_s42"))
f = I.fences(keys)
n = len(f)
o, sp = float(f[0]), float(max(1, f[-1] - f[0]))
raw = [(float(k) - o) / sp for k in f]

units = {r["dataset"]: r for r in json.loads((S / "results/aidb_joint/joint_results.json").read_text())}[DS]
U = units["flow_units"]
warp = lambda x: sum(c * math.tanh(g * (x - m)) for g, m, c in U)
z = [warp(x) for x in raw]
zmin, zspan = min(z), max(z) - min(z)
z = [(v - zmin) / zspan for v in z]

def slots(feature):
    slot, vf, _b, _a, _r = I.smooth_cdf(feature, ALPHA)
    tot = n + len(vf)
    return [s / (tot - 1) for s in slot], len(vf)

ranks = [i / (n - 1) for i in range(n)]
slot_raw, v_raw = slots(raw)
slot_z, v_z = slots(z)

b4 = units["budgets"]["4"]
PANELS = [
    (raw, ranks, "Raw", "key  →  rank", GRAY, units["baseline_linear"], None),
    (z, ranks, "NFL", "z = f(key)  →  rank", ORANGE, units["flow_only"], None),
    (raw, slot_raw, "CSV", "key  →  slot", BLUE, b4["csv_only"], v_raw),
    (z, slot_z, "NFL + CSV", "z = f(key)  →  slot", TEAL, b4["sequential"], v_z),
]

fig = plt.figure(figsize=(13.33, 6.4) if SLIDE else (13.0, 6.2), dpi=200)
fig.patch.set_facecolor("white")
w, gap, left, bot, hgt = 0.207, 0.033, 0.055, 0.195, 0.565
for i, (xs, ys, name, axis_label, colour, probes, virt) in enumerate(PANELS):
    ax = fig.add_axes([left + i * (w + gap), bot, w, hgt]); ax.set_facecolor("white")
    # least-squares line through the points
    mx = sum(xs) / n; my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs); sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    a = sxy / sxx; b = my - a * mx
    ax.plot([0, 1], [b, a + b], color=INK, lw=1.4, ls=(0, (5, 4)), zorder=4)
    ax.plot(xs, ys, color=colour, lw=2.6, zorder=3)
    resid = max(abs(y - (a * x + b)) for x, y in zip(xs, ys))
    ax.set_xlim(-0.03, 1.03); ax.set_ylim(-0.03, 1.03)
    ax.set_xticks([]); ax.set_yticks([])
    for s_ in ("top", "right"): ax.spines[s_].set_visible(False)
    for s_ in ("bottom", "left"): ax.spines[s_].set_color(GRID)
    ax.set_title(name, fontsize=15 if SLIDE else 14, color=colour, loc="left", pad=8, fontweight="semibold")
    ax.set_xlabel(axis_label, fontsize=11 if SLIDE else 10.2, color=MUTED, labelpad=6)
    sub = f"worst gap from the line  {100*resid:.1f}%\n{probes:.2f} probes to find a region"
    if virt: sub += f"\n{virt} virtual points added"
    ax.text(0.97, 0.035, sub, transform=ax.transAxes, va="bottom", ha="right",
            fontsize=10 if SLIDE else 9.3, color=INK, linespacing=1.5)

fig.text(0.055, 0.955, "The fusion idea: a lookup is a map from key to position, and there are two axes you can bend to straighten it",
         fontsize=14.5 if SLIDE else 14, color=INK, fontweight="semibold", va="top")
for i, line in enumerate([
        "NFL bends the INPUT axis, learning a monotone warp z = f(key).   CSV bends the OUTPUT axis, inserting virtual points so the targets become slots instead of ranks.",
        "The dashed line is what the index actually stores: one multiply-add. Everything the curve deviates from it has to be paid for in probes.",
        f"Real data: the {n} region fences of the {DS} 2M sample, the case where both axes matter. Fusion = offer all four as candidates and keep the cheapest."]):
    fig.text(0.055, 0.905 - i * 0.030, line, fontsize=9.7, color=MUTED, va="top")
fig.text(0.055, 0.052, "Both curves rise left to right because both maps are order preserving: bending an axis never reorders the keys.",
         fontsize=9.7, color=MUTED, va="bottom")
fig.text(0.055, 0.012, "Source: data/samples, results/aidb_joint/joint_results.json  ·  generated by results/aidb/fusion_diagram.py",
         fontsize=8, color=MUTED, va="bottom")

out = HERE / ("fusion_diagram_slide.png" if SLIDE else "fusion_diagram.png")
fig.savefig(out, facecolor="white")
print("wrote", out)
for xs, ys, name, _, _, probes, virt in PANELS:
    mx = sum(xs) / n; my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs); sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    a = sxy / sxx; b = my - a * mx
    print(f"  {name:<10} worst gap {100*max(abs(y-(a*x+b)) for x,y in zip(xs,ys)):5.1f}%   probes {probes:6.2f}   virtual {virt}")
