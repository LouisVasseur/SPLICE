#!/usr/bin/env python3
"""Measured throughput: each method alone, and fused, against the noise floor.

Needs matplotlib (outside the stdlib-only pipeline; nothing imports it).
    /usr/bin/python3 results/aidb/throughput_figure.py

Source: results/aidb_final/root_analysis.json, from results/aidb_final/sweep/results.jsonl
(540 paired runs, 20 samples x 9 variants x 3 query seeds, 5M lookups after 500k warm-up,
performance-core QoS, identical query traces). The ten uniform 2M samples are shown.
Speedup = geometric mean over the three query seeds of per-seed throughput ratios against
packed_rank on the same trace.

The noise band is not an assumption: packed_rank_root_vf4 and packed_rank_root_fusion select
the identical structure on every sample (both choose raw key + virtual fences), so the spread
between those two measurements is this host measuring the same index twice.
"""
import json, math, pathlib, statistics
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = pathlib.Path(__file__).resolve().parent
S = HERE.parent.parent
BLUE, TEAL, ORANGE, GRAY, BAND = "#2a78d6", "#1baf7a", "#eb6834", "#9aa5ad", "#e8e7e2"
INK, MUTED, GRID = "#17242f", "#6b7480", "#d8d7d0"

ra = json.loads((S / "results/aidb_final/root_analysis.json").read_text())["per_dataset"]
DS = [d for d in sorted(ra) if d.endswith("_uniform")]
noise = max(abs(ra[d]["packed_rank_root_vf4"]["speedup"] / ra[d]["packed_rank_root_fusion"]["speedup"] - 1) for d in DS)

ROWS = [
    ("sorted_vector", "Plain binary search, no index at all", GRAY),
    ("packed_rank_vp10_root_fusion", "FUSED: CSV in regions + CSV at the root", BLUE),
    ("packed_rank_root_vf4", "CSV alone, at the root", TEAL),
    ("packed_rank_vp10", "CSV alone, in the regions", TEAL),
    ("packed_rank_root_flow", "NFL alone, at the root", ORANGE),
]
gm = lambda xs: math.exp(statistics.mean(math.log(x) for x in xs))

fig = plt.figure(figsize=(12.6, 6.5), dpi=200)
fig.patch.set_facecolor("white")
ax = fig.add_axes([0.315, 0.215, 0.605, 0.545]); ax.set_facecolor("white")
lo, hi = math.log10(0.78), math.log10(2.6)
X = lambda v: (math.log10(v) - lo) / (hi - lo)
ax.set_xlim(0, 1)
ax.axvspan(X(1 - noise), X(1 + noise), color=BAND, zorder=0)
for t in (0.8, 0.9, 1.0, 1.2, 1.5, 2.0, 2.5):
    ax.axvline(X(t), color=GRID, lw=0.8, zorder=1)
ax.axvline(X(1.0), color=INK, lw=1.4, zorder=2)
ax.set_xticks([X(t) for t in (0.8, 0.9, 1.0, 1.2, 1.5, 2.0, 2.5)])
ax.set_xticklabels(["0.8x", "0.9x", "1.0x", "1.2x", "1.5x", "2.0x", "2.5x"], fontsize=10, color=MUTED)

for i, (v, label, colour) in enumerate(ROWS):
    y = len(ROWS) - 1 - i
    vals = [ra[d][v]["speedup"] for d in DS if v in ra[d]]
    for d in DS:
        r = ra[d].get(v)
        if not r: continue
        ax.plot([X(min(max(r["speedup"], 0.78), 2.6))], [y], "o", ms=7.5, color=colour,
                markeredgecolor="white", markeredgewidth=1.4, zorder=4)
    g = gm(vals)
    ax.plot([X(g), X(g)], [y - 0.24, y + 0.24], color=INK, lw=2.6, zorder=5)
    ax.text(1.006, y, f"{g:.2f}x", transform=ax.get_yaxis_transform(), va="center",
            ha="left", fontsize=10.5, color=INK, fontweight="semibold")
    ax.text(-0.012, y, label, transform=ax.get_yaxis_transform(), va="center", ha="right",
            fontsize=11, color=INK)

ax.set_yticks([]); ax.set_ylim(-0.6, len(ROWS) - 0.4)
for s_ in ("top", "right", "left"): ax.spines[s_].set_visible(False)
ax.spines["bottom"].set_color(GRID)
ax.tick_params(axis="x", length=0)
ax.set_xlabel("paired throughput against the packed control on identical query traces (log scale)",
              fontsize=10.5, color=MUTED, labelpad=9)

fig.text(0.02, 0.955, "Throughput: no method moves the clock, alone or fused", fontsize=15.5,
         color=INK, fontweight="semibold", va="top")
for i, line in enumerate([
        "Ten uniform 2M samples, 540 paired runs, 5M lookups per run, performance-core QoS. One dot per dataset; the black tick is the geometric mean.",
        f"The grey band is this host measuring the SAME index twice: two variants that select an identical structure differ by up to {100*noise:.1f} percent.",
        "Probe counts fall by up to 44 percent (see fusion.png) and none of it reaches the clock. Only removing the compression does, which is what the top row shows."]):
    fig.text(0.02, 0.888 - i * 0.036, line, fontsize=9.8, color=MUTED, va="top")
fig.text(0.02, 0.012, "Source: results/aidb_final/root_analysis.json  ·  generated by results/aidb/throughput_figure.py",
         fontsize=8, color=MUTED, va="bottom")
out = HERE / "throughput.png"
fig.savefig(out, facecolor="white")
print("wrote", out, f"(noise floor {100*noise:.1f}%)")
for v, label, _ in ROWS:
    vals = [ra[d][v]["speedup"] for d in DS if v in ra[d]]
    print(f"  {label:<42} geo-mean {gm(vals):.3f}   range {min(vals):.3f}-{max(vals):.3f}")
